#!/usr/bin/env bash
# Generates a large, deterministic, valid Kiln project to measure the web UI.
#   scripts/ui_fixture.sh DIR [PIECES=5000] [BAD=2000]
# Pieces are tiny .gltf files spread over 20 kits. BAD of them carry exactly
# one finding each, cycling through: model_missing (warn), glb_unreadable
# (error), scale (warn), license_not_allowed (error), tris (warn).
# Also: 60 materials, a `world` content set (~300 elements) and a small tree.
set -euo pipefail

DIR="${1:-}"; PIECES="${2:-5000}"; BAD="${3:-2000}"
[ -n "$DIR" ] || { echo "uso: $0 DIR [PIECES] [BAD]" >&2; exit 2; }
case "$PIECES$BAD" in *[!0-9]*) echo "PIECES y BAD deben ser enteros" >&2; exit 2;; esac
[ "$BAD" -le "$PIECES" ] || { echo "BAD no puede superar PIECES" >&2; exit 2; }
if [ -e "$DIR" ] && [ -n "$(ls -A "$DIR" 2>/dev/null)" ]; then
  echo "error: $DIR no esta vacio; no escribo en el" >&2; exit 1
fi

KITS=20
mkdir -p "$DIR/data" "$DIR/godot/astra" "$DIR/kiln" "$DIR/data/content"
for k in $(seq 0 $((KITS - 1))); do mkdir -p "$DIR/kits/kit$(printf %02d "$k")"; done

cat > "$DIR/godot/project.godot" <<'T'
; Godot project of the synthetic UI fixture.

config_version=5

[application]

config/name="Kiln UI fixture"
T

cat > "$DIR/kiln.toml" <<'T'
# Synthetic project generated by scripts/ui_fixture.sh
[project]
name = "Synthetic"
engine = "godot"

[assets]
kits = ["kits"]

[materials]
tables = ["data/materials.toml"]
color_keys = ["color"]

[rules]
licenses = ["CC0", "CC-BY"]
max_tris = 20000

[[levels]]
level = "place"
files = ["data/districts.toml"]
table = "districts"
id = "id"
name = "name"
children = [{ key = "rooms", level = "room" }]

[[levels]]
level = "room"
files = ["data/rooms.toml"]
table = "rooms"
id = "id"
name = "name"
children = [{ key = "props", level = "asset" }]

[tools]
godot_project = "godot"

[content.world]
definitions = ["data/content/**/*.ron"]
manifest = "kiln/content_manifest.json"
greybox = false
id_meta = "astra_id"

[content.world.kinds.Sector]
id = "id"
scene = "scene"

[content.world.kinds.Door]
id = "id"
refs = { connects = "Sector" }
distinct = ["connects"]
node_meta = { connects = "astra_connects" }

[content.world.kinds.Object]
id = "id"
asset = "asset"

[content.world.kinds.Installation]
id = "id"
refs = { sector = "Sector", objects = "Object" }
T

# Kit licences: 14 CC0, 6 CC-BY with an attribution line.
for k in $(seq 0 $((KITS - 1))); do
  n=$(printf %02d "$k")
  if [ "$k" -lt 14 ]; then
    printf '# Licencia\n\nPiezas sinteticas. Licensed under CC0 1.0.\n' > "$DIR/kits/kit$n/LICENSE.md"
  else
    printf '# Licencia\n\nPiezas sinteticas. CC-BY 4.0. Attribution: Kiln fixture.\n' > "$DIR/kits/kit$n/LICENSE.md"
  fi
done

# Pieces, manifests, materials, districts and rooms, in one awk pass.
awk -v dir="$DIR" -v pieces="$PIECES" -v bad="$BAD" -v kits="$KITS" '
function gltf(f, side, count) {
  printf "{\"nodes\":[{\"mesh\":0}],\"meshes\":[{\"primitives\":[{\"attributes\":{\"POSITION\":0}}]}],\"accessors\":[{\"count\":%d,\"min\":[0,0,0],\"max\":[%s,%s,%s]}],\"materials\":[{\"name\":\"m\"}]}\n", count, side, side, side > f
  close(f)
}
BEGIN {
  cats[0]="prop"; cats[1]="wall"; cats[2]="door"; cats[3]="tool"; cats[4]="plant"
  for (i = 0; i < pieces; i++) {
    k = i % kits
    kd = sprintf("%s/kits/kit%02d", dir, k)
    name = sprintf("piece%05d", i)
    # Exactly `bad` pieces, evenly spread, are broken; the kind cycles.
    isbad = (int((i + 1) * bad / pieces) > int(i * bad / pieces))
    kind = isbad ? (nb++ % 5) : -1
    entry = sprintf("\"%s\":{\"category\":\"%s\",\"tags\":[\"t%d\",\"t%d\"],\"used_by\":\"sys%d\"", name, cats[i % 5], i % 7, i % 11, i % 13)
    if (kind == 3) entry = entry ",\"credit\":\"Modelo de Autor " i ", CC-BY-NC\""
    entry = entry "}"
    man[k] = man[k] (man[k] == "" ? "" : ",\n") entry
    side = sprintf("%.2f", 0.5 + (i % 9) * 0.3)
    if (kind == 0) { }                                   # manifest only: model_missing
    else if (kind == 1) { f = kd "/" name ".glb"; printf "not a glb\n" > f; close(f) }
    else if (kind == 2) gltf(kd "/" name ".gltf", "500", 3)  # scale
    else if (kind == 4) gltf(kd "/" name ".gltf", side, 90000) # tris
    else gltf(kd "/" name ".gltf", side, 3 * (1 + i % 40))
  }
  for (k = 0; k < kits; k++) {
    f = sprintf("%s/kits/kit%02d/manifest.json", dir, k)
    printf "{\n%s\n}\n", man[k] > f
    close(f)
  }
  f = dir "/data/materials.toml"
  for (m = 0; m < 60; m++)
    printf "[[materials]]\nid = \"mat%02d\"\nname = \"Material %02d\"\ncolor = [%.2f, %.2f, %.2f]\n\n", m, m, (m % 10) / 10, (m % 7) / 7, (m % 5) / 5 > f
  close(f)
  # Tree: 10 districts, 60 rooms each holding 8 assets (the first pieces).
  fd = dir "/data/districts.toml"; fr = dir "/data/rooms.toml"
  for (d = 0; d < 10; d++) {
    rooms = ""
    for (r = 0; r < 6; r++) {
      rid = sprintf("room%02d_%d", d, r)
      rooms = rooms (r ? ", " : "") "\"" rid "\""
      props = ""
      for (p = 0; p < 8; p++) {
        pi = (d * 48 + r * 8 + p) * 7 % pieces
        props = props (p ? ", " : "") sprintf("\"kit%02d/piece%05d\"", pi % kits, pi)
      }
      printf "[[rooms]]\nid = \"%s\"\nname = \"Room %d.%d\"\nprops = [%s]\n\n", rid, d, r, props > fr
    }
    printf "[[districts]]\nid = \"district%02d\"\nname = \"District %d\"\nrooms = [%s]\n\n", d, d, rooms > fd
  }
  close(fd); close(fr)
}' < /dev/null

# Content set `world`: 60 sectors, 59 doors, 120 objects, 60 installations.
awk -v dir="$DIR" -v pieces="$PIECES" -v kits="$KITS" '
BEGIN {
  S = 60; ron = dir "/data/content/world.ron"; man = dir "/kiln/content_manifest.json"
  print "// Synthetic definitions.\n[" > ron
  for (s = 0; s < S; s++)
    printf "    Sector(id: \"sector:s%02d\", scene: \"res://astra/s%02d.tscn\"),\n", s, s > ron
  for (s = 0; s < S - 1; s++)
    printf "    Door(id: \"door:s%02d_s%02d\", connects: (\"sector:s%02d\", \"sector:s%02d\")),\n", s, s + 1, s, s + 1 > ron
  for (o = 0; o < 120; o++) {
    pi = o * 41 % pieces
    printf "    Object(id: \"object:o%03d\", asset: \"kit%02d/piece%05d\"),\n", o, pi % kits, pi > ron
  }
  for (s = 0; s < S; s++)
    printf "    Installation(id: \"installation:i%02d\", sector: \"sector:s%02d\", objects: [\"object:o%03d\", \"object:o%03d\"]),\n", s, s, s * 2, s * 2 + 1 > ron
  print "]" > ron
  close(ron)
  printf "{\n  \"scenes\": [\n" > man
  for (s = 0; s < S; s++) {
    t = dir "/godot/astra/s" sprintf("%02d", s) ".tscn"
    printf "[gd_scene format=3]\n\n[node name=\"S%02d\" type=\"Node3D\"]\nmetadata/astra_id = \"sector:s%02d\"\n", s, s > t
    kids = ""
    if (s < S - 1) {
      did = sprintf("door:s%02d_s%02d", s, s + 1)
      cs = sprintf("[\"sector:s%02d\", \"sector:s%02d\"]", s, s + 1)
      printf "\n[node name=\"DoorNext\" type=\"Node3D\" parent=\".\"]\nmetadata/astra_id = \"%s\"\nmetadata/astra_connects = %s\n", did, cs > t
      kids = sprintf("{\"meta\":{\"astra_connects\":%s,\"astra_id\":\"%s\"},\"name\":\"DoorNext\"}", cs, did)
    }
    close(t)
    printf "    {\"nodes\":[{\"children\":[%s],\"id\":\"sector:s%02d\",\"meta\":{}}", kids, s > man
    if (s < S - 1)
      printf ",{\"children\":[],\"id\":\"door:s%02d_s%02d\",\"meta\":{\"astra_connects\":[\"sector:s%02d\",\"sector:s%02d\"]}}", s, s + 1, s, s + 1 > man
    printf "],\"scene\":\"res://astra/s%02d.tscn\"}%s\n", s, (s < S - 1 ? "," : "") > man
  }
  printf "  ],\n  \"set\": \"world\",\n  \"version\": 2\n}\n" > man
  close(man)
}' < /dev/null

echo "fixture: $DIR ($PIECES pieces in $KITS kits, $BAD broken)"
